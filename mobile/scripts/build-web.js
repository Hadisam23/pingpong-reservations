// Copies the website pages into www/ for Capacitor and points them at the API server.
//   API_URL=https://book.mycenter.com npm run build
// API_URL defaults to http://localhost:3000, which the iOS Simulator can reach on the Mac.
// SELFTEST=1 adds test/selftest.js, which books a table as a guest by itself (used by test-ios.sh).
const fs = require('fs');
const path = require('path');

function buildWeb({ apiUrl = 'http://localhost:3000', outDir = path.join(__dirname, '..', 'www'), selfTest = false } = {}) {
  const src = path.join(__dirname, '..', '..', 'public');
  const apiBase = apiUrl.replace(/\/+$/, '');

  fs.rmSync(outDir, { recursive: true, force: true });
  fs.cpSync(src, outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'config.js'),
    `// Generated by mobile/scripts/build-web.js\nwindow.PP_CONFIG = ${JSON.stringify({ apiBase })};\n`);

  if (selfTest) {
    // The self-test walks through several screens, so every page loads it
    fs.copyFileSync(path.join(__dirname, '..', 'test', 'selftest.js'), path.join(outDir, 'selftest.js'));
    for (const file of fs.readdirSync(outDir).filter(f => f.endsWith('.html'))) {
      const page = path.join(outDir, file);
      fs.writeFileSync(page, fs.readFileSync(page, 'utf8').replace('</body>', '  <script src="selftest.js"></script>\n</body>'));
    }
  }
  return { outDir, apiBase };
}

if (require.main === module) {
  const { outDir, apiBase } = buildWeb({
    apiUrl: process.env.API_URL || undefined,
    selfTest: process.env.SELFTEST === '1',
  });
  console.log(`Built ${path.relative(process.cwd(), outDir) || outDir} (API: ${apiBase})${process.env.SELFTEST === '1' ? ' with self-test' : ''}`);
}

module.exports = { buildWeb };
